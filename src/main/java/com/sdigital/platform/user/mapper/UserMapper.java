package com.sdigital.platform.user.mapper;

import com.sdigital.platform.user.dto.CreateUserRequest;
import com.sdigital.platform.user.dto.UpdateUserRequest;
import com.sdigital.platform.user.dto.UserAgencyDto;
import com.sdigital.platform.user.dto.UserFunctionDto;
import com.sdigital.platform.user.dto.UserResponse;
import com.sdigital.platform.user.entity.User;
import org.springframework.stereotype.Component;

/**
 * Manual mapper between the {@link User} entity and its DTOs.
 *
 * <p>Pure translation only: no persistence access and no business logic (email
 * normalization and uniqueness checks belong to the service).</p>
 */
@Component
public class UserMapper {

    /**
     * Maps an entity to its read model.
     *
     * <p>{@code keycloakId} is not part of {@link UserResponse}, so it is never exposed.</p>
     */
    public UserResponse toResponse(User user) {
        UserAgencyDto agencyDto = user.getAgency() == null ? null : new UserAgencyDto(
                user.getAgency().getId(),
                user.getAgency().getCode(),
                user.getAgency().getName(),
                user.getAgency().getStatus()
        );
        UserFunctionDto functionDto = user.getFunction() == null ? null : new UserFunctionDto(
                user.getFunction().getId(),
                user.getFunction().getCode(),
                user.getFunction().getName(),
                user.getFunction().getStatus()
        );
        return new UserResponse(
                user.getId(),
                user.getEmail(),
                user.getFirstName(),
                user.getLastName(),
                user.getStatus(),
                agencyDto,
                functionDto,
                user.getCreatedAt(),
                user.getUpdatedAt()
        );
    }

    /**
     * Builds a new entity from a creation request.
     *
     * <p>Only the client-provided fields are applied. The identifier and timestamps are
     * left untouched so they are generated by the JPA lifecycle.</p>
     */
    public User toEntity(CreateUserRequest request) {
        return new User(request.email(), request.firstName(), request.lastName());
    }

    /**
     * Applies the modifiable fields of an update request onto an existing entity.
     *
     * <p>Protected fields ({@code id}, {@code keycloakId}, {@code status}, timestamps)
     * are never modified here.</p>
     */
    public void applyUpdate(User user, UpdateUserRequest request) {
        user.setEmail(request.email());
        user.setFirstName(request.firstName());
        user.setLastName(request.lastName());
    }
}
