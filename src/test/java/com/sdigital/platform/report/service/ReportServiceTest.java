package com.sdigital.platform.report.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import com.sdigital.platform.agency.entity.Agency;
import com.sdigital.platform.agency.repository.AgencyRepository;
import com.sdigital.platform.function.entity.Function;
import com.sdigital.platform.function.repository.FunctionRepository;
import com.sdigital.platform.report.dto.ReportFormat;
import com.sdigital.platform.report.dto.ReportType;
import com.sdigital.platform.user.entity.User;
import com.sdigital.platform.user.entity.UserStatus;
import com.sdigital.platform.user.repository.UserRepository;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.DisplayName;

/**
 * Tests for {@link ReportService} with real PDFBox / Apache POI rendering and mocked
 * repositories. Verifies that generated bytes are well-formed for each type/format.
 */
class ReportServiceTest {

    private final UserRepository userRepository = mock(UserRepository.class);
    private final AgencyRepository agencyRepository = mock(AgencyRepository.class);
    private final FunctionRepository functionRepository = mock(FunctionRepository.class);
    private final ReportService service = new ReportService(userRepository, agencyRepository, functionRepository);

    @Test
    @DisplayName("users PDF report starts with PDF signature")
    void usersPdfIsWellFormed() {
        when(userRepository.findAll()).thenReturn(List.of(sampleUser()));
        byte[] pdf = service.generate(ReportType.USERS, ReportFormat.PDF);
        assertThat(pdf).startsWith("%PDF".getBytes());
        assertThat(pdf.length).isGreaterThan(100);
    }

    @Test
    @DisplayName("users XLSX report is non-empty")
    void usersXlsxIsWellFormed() {
        when(userRepository.findAll()).thenReturn(List.of(sampleUser()));
        byte[] xlsx = service.generate(ReportType.USERS, ReportFormat.XLSX);
        assertThat(xlsx).isNotEmpty();
        assertThat(new String(xlsx, 0, 2, java.nio.charset.StandardCharsets.US_ASCII)).isEqualTo("PK");
    }

    @Test
    @DisplayName("agencies PDF report is well-formed")
    void agenciesPdfIsWellFormed() {
        when(agencyRepository.findAll()).thenReturn(List.of());
        byte[] pdf = service.generate(ReportType.AGENCIES, ReportFormat.PDF);
        assertThat(pdf).startsWith("%PDF".getBytes());
    }

    @Test
    @DisplayName("functions XLSX report is well-formed")
    void functionsXlsxIsWellFormed() {
        when(functionRepository.findAll()).thenReturn(List.of());
        byte[] xlsx = service.generate(ReportType.FUNCTIONS, ReportFormat.XLSX);
        assertThat(xlsx).isNotEmpty();
    }

    @Test
    @DisplayName("unknown report type code is rejected")
    void unknownTypeCodeIsRejected() {
        assertThatThrownBy(() -> ReportType.fromCode("invoices"))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    @DisplayName("unknown report format code is rejected")
    void unknownFormatCodeIsRejected() {
        assertThatThrownBy(() -> ReportFormat.fromCode("csv"))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    @DisplayName("blank type code is rejected")
    void blankTypeCodeIsRejected() {
        assertThatThrownBy(() -> ReportType.fromCode("  "))
                .isInstanceOf(IllegalArgumentException.class);
    }

    private User sampleUser() {
        User user = new User("alice@example.com", "Alice", "Dupont");
        user.setStatus(UserStatus.ACTIVE);
        return user;
    }
}
